  function parse(rows, dy) {
    const px = [];
    let w = 0;
    rows.forEach((r, j) => {
      w = Math.max(w, r.length);
      for (let i = 0; i < r.length; i++) if (r[i] === '#') px.push([i, j + (dy || 0)]);
    });
    return { w, px };
  }
  function rot180(rows) {
    const w = Math.max(...rows.map((r) => r.length));
    const h = rows.length;
    const out = [];
    for (let j = h - 1; j >= 0; j--) out.push(rows[j].padEnd(w, '.').split('').reverse().join(''));
    return out;
  }
