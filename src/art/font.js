  function compile(size) {
    const src = size === 1 ? S1 : S2;
    const acc = size === 1 ? ACC1 : ACC2;
    const capH = size === 1 ? 7 : 11;
    const out = GL[size];
    for (const ch in src) out[ch] = parse(src[ch]);
    out[' '] = { w: size === 1 ? S1_SPACE : S2_SPACE, px: [] };
    for (const ch in ACCENTED) {
      let [base, a] = ACCENTED[ch];
      if (size === 2) base = base === 'ı' ? 'I' : base.toUpperCase();
      const b = out[base];
      if (!b) continue;
      const lower = size === 1 && base === base.toLowerCase() && base !== base.toUpperCase() || base === 'ı';
      const arows = acc[a];
      const aw = Math.max(...arows.map((r) => r.length));
      const w = Math.max(b.w, aw);
      const bx = Math.floor((w - b.w) / 2);
      const ax = Math.ceil((w - aw) / 2);
      // filas del acento: mayúsculas 3px por encima (con 1px de aire); minúsculas sobre la x-height
      const top = lower ? (arows.length === 1 ? 0 : -1) : -(arows.length + 1);
      const px = b.px.map(([x, y]) => [x + bx, y]);
      arows.forEach((r, j) => { for (let i = 0; i < r.length; i++) if (r[i] === '#') px.push([i + ax, top + j]); });
      out[ch] = { w, px };
    }
    for (const ch in out) {
      const g = out[ch];
      let t = 0, b = capH - 1;
      g.px.forEach(([, y]) => { if (y < t) t = y; if (y > b) b = y; });
      g.top = t; g.bot = b;
    }
  }
